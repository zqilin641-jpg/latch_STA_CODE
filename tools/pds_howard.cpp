// Direct parameterized difference graph; no latch-only .out model conversion.
#include <fstream>
#include <iomanip>
#include <iostream>
#include "howard.hpp"

int main(int argc, char **argv) {
    if (argc != 2) return 1;
    std::ifstream input(argv[1]);
    std::string magic;
    size_t n, m;
    double t0;
    if (!(input >> magic >> n >> m >> t0) || magic != "PDS_GRAPH_V1" ||
        n == 0 || n > 1000000 || m > 10000000 || !std::isfinite(t0) || t0 <= 0) return 1;
    Graph graph;
    for (size_t i = 0; i < n; ++i)
        boost::add_vertex(NodeProperties{i, std::to_string(i), "phase"}, graph);
    for (size_t i = 0; i < m; ++i) {
        size_t u, v;
        double weight, transit;
        std::string id;
        if (!(input >> u >> v >> weight >> transit >> id) || u >= n || v >= n ||
            !std::isfinite(weight) || !std::isfinite(transit) ||
            id.empty() || id.find_first_not_of("0123456789") != std::string::npos) return 1;
        boost::add_edge(u, v, ArcProperties{0, weight, transit, id}, graph);
    }
    std::string trailing;
    if (input >> trailing) return 1;
    Howard solver(graph, n, t0, 1e-9);
    solver.run();
    const auto &result = solver.getResult();
    std::cout << std::setprecision(17) << "{\"status\":\"" << statusName(result.status) << "\"";
    if (result.status != HowardStatus::Converged) {
        std::cout << ",\"period_ns\":null}\n";
        return 2;
    }
    std::cout << ",\"period_ns\":" << result.period
              << ",\"max_violation\":" << result.maxViolation
              << ",\"cycle_residual\":" << result.cycleResidual
              << ",\"iterations\":" << result.iterations << ",\"cycle\":[";
    bool first = true;
    for (const auto edge : solver.getCycle()) {
        if (!first) std::cout << ',';
        first = false;
        // IDs are numeric in the interchange format generated by the bridge.
        std::cout << '"' << graph[edge].constraintType << '"';
    }
    std::cout << "]}\n";
    return 0;
}
